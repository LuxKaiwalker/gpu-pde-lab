#!/usr/bin/env python3
"""Measure every heat-step implementation against the memory roofline.

Produces three artifacts, all meant to be committed:

    docs/results/roofline.png   the figure
    docs/results/roofline.csv   the raw numbers behind it
    docs/results/roofline.md    device, versions and a summary table

Usage:
    python scripts/run_roofline.py
    python scripts/run_roofline.py --sizes 256 512 1024 2048 4096 --precision fp32
    python scripts/run_roofline.py --impls baseline triton --out-dir /tmp/rl
"""

from __future__ import annotations

import argparse
import csv
import datetime as _dt
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from gpu_pde_lab.benchmarking.roofline import (
    run_roofline_sweep,
)
from gpu_pde_lab.core.backend import cuda_free_memory_bytes, cuda_is_usable
from gpu_pde_lab.core.boundary import BoundaryKind
from gpu_pde_lab.kernels.registry import available_implementations

CSV_COLUMNS = [
    "impl", "n", "precision", "boundary", "seconds_per_step", "cells_per_second",
    "array_passes", "wasted_traffic_factor", "useful_bytes_per_step",
    "achieved_useful_gb_s", "copy_ceiling_gb_s", "peak_gb_s",
    "fraction_of_peak", "fraction_of_achievable", "max_abs_diff_from_baseline",
]


def _write_csv(path: Path, sweep) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        for m in sweep.measurements:
            writer.writerow({
                "impl": m.impl,
                "n": m.n,
                "precision": sweep.precision,
                "boundary": sweep.boundary,
                "seconds_per_step": f"{m.seconds_per_step:.9e}",
                "cells_per_second": f"{m.cells_per_second:.6e}",
                "array_passes": m.array_passes,
                "wasted_traffic_factor": (
                    f"{m.wasted_traffic_factor:.1f}" if m.wasted_traffic_factor else ""),
                "useful_bytes_per_step": m.useful_bytes_per_step,
                "achieved_useful_gb_s": f"{m.achieved_bandwidth_bytes_per_s / 1e9:.3f}",
                "copy_ceiling_gb_s": f"{m.copy_ceiling_bytes_per_s / 1e9:.3f}",
                "peak_gb_s": f"{m.peak_bandwidth_bytes_per_s / 1e9:.3f}",
                "fraction_of_peak": f"{m.fraction_of_peak:.4f}",
                "fraction_of_achievable": f"{m.fraction_of_achievable:.4f}",
                "max_abs_diff_from_baseline": f"{m.max_abs_diff_from_baseline:.3e}",
            })


def _write_markdown(path: Path, sweep) -> None:
    lines: list[str] = []
    lines.append("# Roofline results")
    lines.append("")
    lines.append(
        "Generated by `scripts/run_roofline.py`. Every number here is measured on "
        "the machine named below; re-running on different hardware will produce "
        "different numbers, which is why the device is recorded alongside them."
    )
    lines.append("")
    stamp = _dt.datetime.now(_dt.UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines.append(f"- **Measured** {stamp}")
    if sweep.device:
        lines.append(f"- **Device** {sweep.device.summary()}")
    lines.append(f"- **Precision** {sweep.precision} | **Boundary** {sweep.boundary}")
    lines.append(f"- **Timing** {sweep.steps_per_measurement} steps per measurement, "
                 "synchronized before and after")
    lines.append("")

    lines.append("## Implementations")
    lines.append("")
    lines.append("| Implementation | What it is | Kernels/step | Array passes/step |")
    lines.append("|---|---|---|---|")
    for d in available_implementations():
        passes = f"{d.array_passes:.1f}" if d.array_passes is not None else "fused (n/a)"
        lines.append(f"| `{d.name}` | {d.description} | {d.kernel_launches} | {passes} |")
    lines.append("")

    if sweep.skipped:
        lines.append("Not measured in this run:")
        lines.append("")
        for name, why in sweep.skipped.items():
            lines.append(f"- `{name}` -- {why}")
        lines.append("")

    impls = sweep.impls_present()
    if impls:
        lines.append("## Achieved useful bandwidth (GB/s)")
        lines.append("")
        lines.append(
            "Useful bytes -- one read of the field plus one write, the irreducible "
            "traffic of a stencil update -- divided by measured time. Every "
            "implementation is scored against the same numerator, so an "
            "implementation that moves more memory than it needs to shows up as a "
            "lower figure rather than being credited for the waste."
        )
        lines.append("")
        header = "| N | " + " | ".join(f"`{i}`" for i in impls) + " | copy ceiling | peak |"
        lines.append(header)
        lines.append("|" + "---|" * (len(impls) + 3))
        for n in sweep.sizes:
            row = [str(n)]
            ceiling = peak = float("nan")
            for impl in impls:
                ms = [m for m in sweep.by_impl(impl) if m.n == n]
                if ms:
                    row.append(f"{ms[0].achieved_bandwidth_bytes_per_s / 1e9:.1f}")
                    ceiling = ms[0].copy_ceiling_bytes_per_s / 1e9
                    peak = ms[0].peak_bandwidth_bytes_per_s / 1e9
                else:
                    row.append("--")
            row.append(f"{ceiling:.1f}")
            row.append(f"{peak:.1f}")
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

        lines.append("## Fraction of the achievable (memcpy) ceiling")
        lines.append("")
        lines.append("| N | " + " | ".join(f"`{i}`" for i in impls) + " |")
        lines.append("|" + "---|" * (len(impls) + 1))
        for n in sweep.sizes:
            row = [str(n)]
            for impl in impls:
                ms = [m for m in sweep.by_impl(impl) if m.n == n]
                row.append(f"{ms[0].fraction_of_achievable * 100:.0f}%" if ms else "--")
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

        lines.append("## Speedup over the eager baseline")
        lines.append("")
        table = sweep.speedup_table()
        others = [i for i in impls if i != "baseline"]
        if others:
            lines.append("| N | " + " | ".join(f"`{i}`" for i in others) + " |")
            lines.append("|" + "---|" * (len(others) + 1))
            for n in sweep.sizes:
                row = [str(n)]
                for impl in others:
                    v = table.get(impl, {}).get(n)
                    row.append(f"{v:.2f}x" if v else "--")
                lines.append("| " + " | ".join(row) + " |")
            lines.append("")

        worst = max((m.max_abs_diff_from_baseline for m in sweep.measurements
                     if m.impl != "baseline"), default=0.0)
        lines.append("## Correctness")
        lines.append("")
        lines.append(
            f"Every implementation's output was compared against the baseline's at "
            f"every grid size in this run. Worst absolute difference: **{worst:.3e}** "
            f"-- rounding, not disagreement, at {sweep.precision}."
        )
        lines.append("")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_plot(path: Path, sweep) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    impls = sweep.impls_present()
    if not impls:
        return

    fig, axes = plt.subplots(1, 3, figsize=(16.5, 4.8))
    colors = {
        "baseline": "#999999",
        "cuda_graph": "#d08020",
        "compiled": "#3080c0",
        "triton": "#20a060",
    }

    # -- 1. achieved bandwidth against both ceilings ----------------------
    ax = axes[0]
    for impl in impls:
        ms = sorted(sweep.by_impl(impl), key=lambda m: m.n)
        ax.plot([m.n for m in ms], [m.achieved_bandwidth_bytes_per_s / 1e9 for m in ms],
                "o-", label=impl, color=colors.get(impl))
    ms_any = sorted(sweep.measurements, key=lambda m: m.n)
    if ms_any:
        ns = sorted({m.n for m in ms_any})
        ceilings = [next(m.copy_ceiling_bytes_per_s / 1e9 for m in ms_any if m.n == n) for n in ns]
        ax.plot(ns, ceilings, "k--", label="memcpy ceiling", linewidth=1.3)
        peak = ms_any[0].peak_bandwidth_bytes_per_s / 1e9
        ax.axhline(peak, color="k", linestyle=":", linewidth=1.3,
                   label=f"spec peak ({peak:.0f} GB/s)")
    ax.set_xscale("log", base=2)
    ax.set_xlabel("N  (grid is N x N)")
    ax.set_ylabel("achieved useful bandwidth (GB/s)")
    ax.set_title("Useful bandwidth vs the roofline")
    ax.legend(fontsize=8)
    ax.grid(True, which="both", alpha=0.3)

    # -- 2. fraction of the achievable ceiling ----------------------------
    ax = axes[1]
    for impl in impls:
        ms = sorted(sweep.by_impl(impl), key=lambda m: m.n)
        ax.plot([m.n for m in ms], [m.fraction_of_achievable * 100 for m in ms],
                "o-", label=impl, color=colors.get(impl))
    ax.axhline(100, color="k", linestyle="--", linewidth=1.2)
    ax.set_xscale("log", base=2)
    ax.set_xlabel("N  (grid is N x N)")
    ax.set_ylabel("% of memcpy ceiling")
    ax.set_title("Fraction of achievable bandwidth")
    ax.legend(fontsize=8)
    ax.grid(True, which="both", alpha=0.3)

    # -- 3. time per step -------------------------------------------------
    ax = axes[2]
    for impl in impls:
        ms = sorted(sweep.by_impl(impl), key=lambda m: m.n)
        ax.loglog([m.n for m in ms], [m.seconds_per_step * 1e3 for m in ms],
                  "o-", label=impl, color=colors.get(impl))
    ax.set_xlabel("N  (grid is N x N)")
    ax.set_ylabel("ms / step")
    ax.set_title("Time per heat step")
    ax.legend(fontsize=8)
    ax.grid(True, which="both", alpha=0.3)

    device_line = sweep.device.summary() if sweep.device else "no CUDA device"
    fig.suptitle(
        f"GPU PDE Lab -- fused 5-point stencil, {sweep.precision}, "
        f"{sweep.boundary} boundary\n{device_line}",
        fontsize=9,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.90))
    fig.savefig(path, dpi=140)
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                      formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sizes", type=int, nargs="+",
                        default=[128, 256, 512, 1024, 2048, 4096, 8192])
    parser.add_argument("--precision", choices=["fp16", "fp32", "fp64"], default="fp32")
    parser.add_argument("--boundary", choices=[b.value for b in BoundaryKind], default="neumann")
    parser.add_argument("--steps", type=int, default=50)
    parser.add_argument("--impls", nargs="+", default=None,
                        help="subset of implementations (default: all available)")
    parser.add_argument("--out-dir", type=str, default="docs/results")
    args = parser.parse_args()

    if not cuda_is_usable():
        free = cuda_free_memory_bytes()
        detail = (f"only {free / 1024 ** 2:.0f} MB free" if free is not None
                  else "no usable device")
        print(f"The roofline sweep needs a CUDA device ({detail}).", file=sys.stderr)
        for d in available_implementations():
            if not d.available:
                print(f"  {d.name}: {d.unavailable_reason}", file=sys.stderr)
        return 1

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"Sweeping sizes={args.sizes} precision={args.precision} "
          f"boundary={args.boundary} steps={args.steps}")
    for d in available_implementations():
        mark = "ok" if d.available else f"skip ({d.unavailable_reason})"
        print(f"  {d.name:12s} {mark}")
    print()

    sweep = run_roofline_sweep(
        args.sizes,
        precision=args.precision,
        boundary=BoundaryKind(args.boundary),
        n_steps=args.steps,
        impls=args.impls,
    )

    if sweep.device:
        print(sweep.device.summary())
        print()

    header = (f"{'impl':<12} {'N':>6} {'ms/step':>10} {'Gcell/s':>9} {'GB/s':>8} "
              f"{'%peak':>7} {'%memcpy':>8} {'waste':>7} {'err':>10}")
    print(header)
    print("-" * len(header))
    for m in sweep.measurements:
        print(f"{m.impl:<12} {m.n:>6} {m.seconds_per_step * 1e3:>10.4f} "
              f"{m.cells_per_second / 1e9:>9.2f} "
              f"{m.achieved_bandwidth_bytes_per_s / 1e9:>8.1f} "
              f"{m.fraction_of_peak * 100:>6.1f}% {m.fraction_of_achievable * 100:>7.1f}% "
              f"{(f'{m.wasted_traffic_factor:.1f}x' if m.wasted_traffic_factor else '-'):>7} "
              f"{m.max_abs_diff_from_baseline:>10.2e}")
    print()

    table = sweep.speedup_table()
    for impl, rows in table.items():
        if rows:
            best = max(rows.values())
            print(f"{impl:<12} speedup over baseline: "
                  f"{min(rows.values()):.2f}x .. {best:.2f}x")

    csv_path = out_dir / "roofline.csv"
    md_path = out_dir / "roofline.md"
    png_path = out_dir / "roofline.png"
    _write_csv(csv_path, sweep)
    _write_markdown(md_path, sweep)
    try:
        _write_plot(png_path, sweep)
    except ImportError:
        print("matplotlib not installed; skipped the figure", file=sys.stderr)
        png_path = None

    print()
    print(f"Wrote {csv_path}")
    print(f"Wrote {md_path}")
    if png_path:
        print(f"Wrote {png_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
